/** A unit id as words (`energy_security` → `energy security`). */
export function unitWords(id: string): string {
  return id.replace(/[_-]+/g, ' ').trim() || id
}

export interface Nouns {
  subject: string
  subjects: string
  unit: string
  units: string
  /** The grader's pair noun: "<subject> × <unit> pairs". */
  pairs: string
}

export function nouns(ui: ProfileUi = PROFILE_UI): Nouns {
  const subject = ui.subject.singular.toLowerCase()
  const unit = ui.unit_noun.singular.toLowerCase()
  return {
    subject,
    subjects: ui.subject.plural.toLowerCase(),
    unit,
    units: ui.unit_noun.plural.toLowerCase(),
    pairs: `${subject} × ${unit} pairs`,
  }
}

