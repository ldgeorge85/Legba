export type StageId = 'entries' | 'resolved' | 'scored' | 'voided' | 'awaiting'
export const STAGE_ORDER: readonly StageId[] = ['entries', 'resolved', 'scored', 'voided', 'awaiting']
export const STAGE_LABEL: Record<StageId, string> = {
  entries: 'Entries',
  resolved: 'Resolved',
  scored: 'Scored',
  voided: 'Voided',
  awaiting: 'Awaiting a judge',
}

export interface LedgerStage {
  id: StageId
  label: string
  count: FigureData
  /** The denominator the count is read against — itself a figure. */
  of: { label: string; figure: FigureData }
  /** The route the count came from, or why there is none. */
  route: string
  note?: string
}

export interface Ledger {
  id: 'forecast' | 'goldset'
  title: string
  definition: string
  stages: LedgerStage[]
  /** Why the stages that read *not measured* do, said once for the table. */
  gap?: string
}

/* The forecast ledger's stage table (entries/resolved/voided read "not measured
 * (no route)") was removed 2026-11-13: the sealed forecast ledger has a live
 * read (`/v3/ledger/forecasts`, `/v3/ledger/scorecard`) and ONE home,
 * `panels/ledger/ForecastLedger.tsx`, which the Accuracy page mounts in this
 * section's place. The acute pilot's scored count stays in the calibration
 * section (`evalOps` acute BSS line). */

export function goldsetLedger(i: AccuracyInputs): Ledger {
  const fig = (value: unknown, unit: string, asOf: AsOf) => figOf(i, 'correctness', value, unit, asOf)
  const corr = correctnessOf(i)
  const asOf = asOfFrom(corr ? i.readAt : null, 'the route did not answer', READ_LIVE)
  const weeks = Array.isArray(corr?.labeling?.weeks) ? corr!.labeling.weeks! : null
  const sampled = weeks ? weeks.reduce((a, w) => a + (isNum(w.sampled) ? w.sampled : 0), 0) : null
  const labeled = weeks ? weeks.reduce((a, w) => a + (isNum(w.labeled) ? w.labeled : 0), 0) : null
  const fleet = obj<NonNullable<UnitCorrectnessBoard['fleet']>>(corr?.fleet)
  const fleetAsOf: AsOf = fleet ? asOf : { absent: 'the route reports no fleet row — no verdict was read' }
  const sampledFig = fig(sampled, 'findings sampled', asOf)
  const labelledFig = fig(fleet?.n_labels, 'verdicts labelled', fleetAsOf)
  return {
    id: 'goldset',
    title: 'Operator gold-set ledger',
    definition:
      'The weekly sample of findings pinned for the operator to judge. A sampled finding is ' +
      'resolved when the operator labels it, scored when the label is a verdict, voided when ' +
      'the operator marks it unresolvable (held out of both numerator and denominator), and ' +
      'awaiting a judge until it is labelled. The scored and voided rows count every label ' +
      'ever given; the other three count only the pinned weeks.',
    stages: [
      {
        id: 'entries',
        label: STAGE_LABEL.entries,
        count: sampledFig,
        of: { label: 'weeks pinned', figure: fig(corr?.labeling?.weeks_pinned, 'weeks', asOf) },
        route: '/v3/eval/correctness · labeling',
      },
      {
        id: 'resolved',
        label: STAGE_LABEL.resolved,
        count: fig(labeled, 'findings labelled', asOf),
        of: { label: 'sampled', figure: sampledFig },
        route: '/v3/eval/correctness · labeling',
      },
      {
        id: 'scored',
        label: STAGE_LABEL.scored,
        count: fig(fleet?.n_scored, 'verdicts', fleetAsOf),
        of: { label: 'labelled, every week', figure: labelledFig },
        route: '/v3/eval/correctness · fleet',
      },
      {
        id: 'voided',
        label: STAGE_LABEL.voided,
        count: fig(fleet?.n_unresolvable, 'verdicts unresolvable', fleetAsOf),
        of: { label: 'labelled, every week', figure: labelledFig },
        route: '/v3/eval/correctness · fleet',
      },
      {
        id: 'awaiting',
        label: STAGE_LABEL.awaiting,
        count: fig(sampled !== null && labeled !== null ? sampled - labeled : null, 'findings', asOf),
        of: { label: 'sampled', figure: sampledFig },
        route: '/v3/eval/correctness · labeling',
      },
    ],
  }
}

