/** An ISO instant as a compact UTC stamp (`2026-10-04 09:20Z`), or null. */
export function stampOf(iso: string | null | undefined): string | null {
  if (typeof iso !== 'string') return null
  const t = Date.parse(iso)
  if (!Number.isFinite(t)) return null
  return `${new Date(t).toISOString().slice(0, 16).replace('T', ' ')}Z`
}

/** An as-of from an ISO instant, or the stated reason there is none. */
export function asOfFrom(iso: string | null | undefined, whyAbsent: string, suffix = ''): AsOf {
  const s = stampOf(iso)
  return s ? `${s}${suffix}` : { absent: whyAbsent }
}

function isNum(v: unknown): v is number {
  return typeof v === 'number' && Number.isFinite(v)
}

/** A count that is a number → measured; anything else → *not measured*. */
export function fig(value: unknown, unit: string, asOf: AsOf): FigureData {
  return isNum(value) ? { state: 'measured', value, unit, asOf } : { state: 'not_measured', unit, asOf }
}

function obj<T>(v: unknown): T | null {
  return v && typeof v === 'object' && !Array.isArray(v) ? (v as T) : null
}

/** The suffix on an as-of that the client stamped, not the route. */
export const READ_LIVE = ' (read live)'

