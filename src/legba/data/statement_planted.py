def _date_spans(text: str) -> list[tuple[int, int]]:
    return [d.span for d in find_dates(text)]


def bump_first_number(text: str, *, step: int = 1) -> str | None:
    """``text`` with its first non-date figure changed to a different value in
    the same spelling style, or ``None`` if it states none. ``step`` > 1
    moves it further (the planter retries when a quote happens to state the
    first bumped value)."""
    nums = find_numbers(text, skip=_date_spans(text), words="none")
    if not nums:
        return None
    n = nums[0]
    raw = re.match(r"[\d,.]+", n.raw)
    if raw is None:
        return None
    digits = raw.group(0).rstrip(".,")
    if "." in digits:
        places = len(digits.split(".")[1])
        new = f"{float(digits.replace(',', '')) * (1 + 0.5 * step) + 0.7 * step:.{places}f}"
    else:
        value = int(digits.replace(",", ""))
        bumped = value + step * max(2, value // 4 + 1)
        new = f"{bumped:,}" if "," in digits else str(bumped)
    start = n.span[0]
    return text[:start] + new + text[start + len(digits):]


def _quotes(support: Sequence[SupportRow]) -> list[str]:
    return [r.quote or "" for r in support if enum_value(r.role) == "evidence"]


def _numbers_unsupported(text: str, support: Sequence[SupportRow]) -> list[str]:
    _, missing = unsupported_figures(text, evidence_figures(_quotes(support)))
    return [f.raw for f in missing]


def _dates_unsupported(text: str, support: Sequence[SupportRow]) -> list[str]:
    ev = [EvidenceDating(r.quote or "", r.published_at) for r in support if enum_value(r.role) == "evidence"]
    return list(judge_dates(text, ev).missing)


def _shift_date(text: str, attempt: int = 0) -> tuple[str, int, int] | None:
    """``(text, day_delta, month_delta)`` with the first date moved; each
    ``attempt`` moves it a different distance."""
    dates = find_dates(text)
    if not dates:
        return None
    d = dates[0]
    a, b = d.span
    if d.day is not None:
        delta = (3, -3, 5, -5, 9, -9)[attempt % 6]
        new_day = d.day + delta
        if not 1 <= new_day <= 28:
            new_day = d.day - delta
        if not 1 <= new_day <= 28 or new_day == d.day:
            return None
        raw = re.sub(rf"(?<!\d){d.day}(?!\d)", str(new_day), d.raw, count=1)
        return text[:a] + raw + text[b:], new_day - d.day, 0
    step = (1, 2, 3)[attempt % 3]
    new_month = (d.month - 1 + step) % 12 + 1
    raw = re.sub(_MONTHS[d.month - 1], _MONTHS[new_month - 1], d.raw, count=1, flags=re.IGNORECASE)
    return text[:a] + raw + text[b:], 0, new_month - d.month


def _swap_text(texts: EvidenceTexts, old: str, new: str) -> EvidenceTexts | None:
    """Every stored text (page texts and feed items) with ``old`` replaced by
    ``new``; ``None`` if ``old`` occurs in none of them."""
    hit = False

    def sub(v: str) -> str:
        nonlocal hit
        if old in v:
            hit = True
            return v.replace(old, new)
        return v

    swapped = EvidenceTexts(
        by_fetch_version={k: sub(v) for k, v in dict(texts.by_fetch_version).items()},
        by_fetch_item={k: sub(v) for k, v in dict(texts.by_fetch_item).items()},
        by_signal={k: sub(v) for k, v in dict(texts.by_signal).items()},
        by_observation=dict(texts.by_observation),
        by_knowledge_item_version=dict(texts.by_knowledge_item_version),
        feed_item_by_signal={k: tuple(sub(t) for t in v)
                             for k, v in dict(texts.feed_item_by_signal or {}).items()},
    )
    return swapped if hit else None


def _all_texts(texts: EvidenceTexts) -> list[str]:
    out = list(dict(texts.by_signal).values()) + list(dict(texts.by_fetch_version).values())
    for v in dict(texts.feed_item_by_signal or {}).values():
        out.extend(v)
    return out


def _negate(quote: str) -> str | None:
    for aux in (" has been ", " have been ", " is ", " was ", " were ", " has ", " have ", " will "):
        if aux in quote:
            return quote.replace(aux, f"{aux}not ", 1)
    return None


def _rewrite_every_quote(
    support: Sequence[SupportRow], texts: EvidenceTexts, rewrite: Any,
) -> tuple[tuple[SupportRow, ...], EvidenceTexts] | None:
    """Every EVIDENCE quote rewritten (and the stored text with it), or
    ``None`` when any one cannot be: a plant must leave no quote that still
    supports the statement (S-6 — the S-5 artefact was a planted quote that
    was one of several)."""
    out: list[SupportRow] = []
    for row in support:
        if enum_value(row.role) != "evidence":
            out.append(row)
            continue
        quote = row.quote or ""
        new = rewrite(quote)
        if not quote or new is None or new == quote:
            return None
        swapped = _swap_text(texts, quote, new)
        if swapped is None:
            return None
        texts = swapped
        # the old quote's context would show the TRUE text: dropped
        out.append(replace(row, quote=new, quote_context=None))
    return tuple(out), texts


def plant(item: SeatItem, kind: str, *, index: int = 0) -> SeatItem | None:
    """One planted item of ``kind`` derived from the true ``item``; ``None``
    when the base has nothing to plant that error in. Deterministic.

    S-6 — NO OTHER SUPPORTING QUOTE. A planted error is wrong against EVERY
    quote the item carries: a changed figure or date is one no quote states
    (checked by the gate's own readers; the planter moves it further until
    none does), a quote from "another version" or a "claim" frame replaces
    EVERY quote, and the wrong subject is a name no stored text carries."""
    st = item.statement
    text = strip_markers(st.text)
    new_st: StatementDraft | None = None
    support, texts = item.support, item.texts
    if kind == "wrong_number":
        if _numbers_unsupported(text, support):
            return None                  # the base is not clean: no clean plant
        for step in range(1, 6):
            bumped = bump_first_number(text, step=step)
            if bumped is None:
                return None
            if _numbers_unsupported(bumped, support):
                new_st = replace(st, text=bumped)
                break
        if new_st is None:
            return None
    elif kind == "wrong_date":
        if _dates_unsupported(text, support):
            return None
        for attempt in range(6):
            shifted = _shift_date(text, attempt)
            if shifted is None:
                return None
            new_text, dd, dm = shifted
            if not _dates_unsupported(new_text, support):
                continue                 # a quote or a publication day carries it: move on
            vf = st.valid_from
            if isinstance(vf, datetime):
                try:
                    vf = vf.replace(day=vf.day + dd) if dd else vf.replace(month=((vf.month - 1 + dm) % 12) + 1)
                except ValueError:
                    vf = st.valid_from
            new_st = replace(st, text=new_text, valid_from=vf)
            break
        if new_st is None:
            return None
    elif kind == "wrong_subject":
        names = sorted({n for n in item.subject_names if n and n in text}, key=len, reverse=True)
        stored = _all_texts(item.texts)
        foil = next((f for f in FOIL_NAMES[index % len(FOIL_NAMES):] + FOIL_NAMES
                     if not any(f in t for t in stored) and f not in text), None)
        if not names or foil is None:
            return None
        new_text = text
        for name in names:
            new_text = new_text.replace(name, foil)
        if any(n and n in new_text for n in item.subject_names):
            return None                  # the true subject is still named
        new_st = replace(st, text=new_text)
    elif kind in {"other_version_quote", "claim_as_fact"}:
        if not _quotes(support):
            return None
        if kind == "claim_as_fact":
            if enum_value(st.kind) == "attributed":
                return None
            party = CLAIM_PARTIES[index % len(CLAIM_PARTIES)]

            def rewrite(quote: str) -> str:
                head, _, rest = quote.partition(" ")
                tail = f"{head.lower()} {rest}" if head in {"A", "An", "The"} else quote
                return f"{party} claimed that {tail}"
        else:
            def rewrite(quote: str) -> str | None:
                return bump_first_number(quote) or _negate(quote)
        done = _rewrite_every_quote(support, texts, rewrite)
        if done is None:
            return None
        support, texts = done
        new_st = st
    elif kind == "unsupported_inference":
        clause = INFERENCE_CLAUSES[index % len(INFERENCE_CLAUSES)]
        new_st = replace(st, text=text.rstrip(". ") + clause + ".")
    else:
        raise ValueError(f"unknown planted kind {kind!r}")
    return SeatItem(f"{item.item_id}:{kind}", kind, new_st, support, texts,
                    item.subject_names, item.base_id)


def planted_set(
    bases: Sequence[SeatItem], *, per_kind: int = 4, true_controls: int = 6,
) -> list[SeatItem]:
    """``per_kind`` planted items of each kind plus ``true_controls`` true
    items, chosen deterministically: each kind starts at a different base
    (rotation by kind) so no single base carries a kind's whole rate."""
    out: list[SeatItem] = []
    n = len(bases)
    for k, kind in enumerate(PLANTED_KINDS):
        taken = 0
        for step in range(n):
            if taken >= per_kind:
                break
            made = plant(bases[(k * per_kind + step) % n], kind, index=taken)
            if made is not None:
                out.append(made)
                taken += 1
    stride = max(1, n // max(1, true_controls))
    out.extend(bases[(i * stride + 1) % n] for i in range(min(true_controls, n)))
    return out


