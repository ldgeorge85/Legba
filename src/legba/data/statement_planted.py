"""Planted wrong statements, and the verifier's catch rate on them.
The verifier is measured on its catch rate on planted items and its
false-reject rate on true items. Pre-set floors: catch ≥ 0.90, false reject
≤ 0.15.

THE SIX PLANTED ERRORS, each generated by code from a known-true item, never
by a model, so the same base always yields the same planted item:

==========================  ===================================================
``wrong_number``            the statement's first figure is changed; the quote
                            still states the true one
``wrong_date``              the statement's first date (and its valid-from) is
                            moved; the quote still states the true one
``wrong_subject``           the statement names a different subject; the quote
                            names the true one
``other_version_quote``     the quote is the one a DIFFERENT version of the
                            page carries (its figure changed, or negated); the
                            statement still says what the cited version said
``unsupported_inference``   the statement adds a cause, intent or forecast no
                            quote states
``claim_as_fact``           the quote attributes the content to a party ("X
                            claimed that …"); the statement records it as fact
==========================  ===================================================

THE RATES. ``catch`` = planted items the seat does not establish; ``false
reject`` = true items it does not establish. Both come with their n and a 95 %
Wilson interval, and both are reported twice: for the SEAT end to end (code
first, then the model) and for the MODEL alone (its verdicts on every item,
code ignored) — so a model that cannot discriminate cannot hide behind the
code checks that caught the easy plants. Below :data:`CATCH_FLOOR`,
:func:`establishment_paused` is true: candidates accumulate, nothing is lost.

A small sample is a small sample: at n = 24 one miss moves the rate by about
0.04, and the interval says so.

S-6 — NO OTHER SUPPORTING QUOTE. S-5 found planted "misses" that were
artefacts: the planted quote was one of several and the others still
supported the statement. Every plant is now wrong against EVERY quote of its
item (:func:`plant`), and plants are made on real pieces as well as on the
canary and the paraphrase controls (``statement_seat_canary.CONTROLS``).

Pure; stdlib + the gate's content readers.
"""
from __future__ import annotations

import math
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, replace
from datetime import datetime
from typing import Any

from .statement_content import find_dates, find_numbers, strip_markers
from .statement_dates import EvidenceDating, judge_dates
from .statement_numbers import evidence_figures, unsupported_figures
from .statement_seat_canary import CanaryItem
from .statement_shapes import EvidenceTexts, StatementDraft, SupportRow, enum_value
from .statement_verifier import SUPPORTS, UNCLEAR, VerifierReport

#: Plan S3's pre-set floors. Not tuned to any test set.
CATCH_FLOOR = 0.90
FALSE_REJECT_CEILING = 0.15

TRUE = "true"
PLANTED_KINDS: tuple[str, ...] = (
    "wrong_number", "wrong_date", "wrong_subject",
    "other_version_quote", "unsupported_inference", "claim_as_fact",
)

#: Invented names for ``wrong_subject`` (never a real place or body).
FOIL_NAMES = ("Westmarch", "Dunmore Flats", "Pellingham", "Aldercourt", "Greyhaven", "Sallow Reach")
#: Clauses for ``unsupported_inference``: a cause, an intent, a forecast.
INFERENCE_CLAUSES = (
    ", a step taken to pressure neighbouring governments",
    ", which will push prices sharply higher next quarter",
    ", in retaliation for earlier sanctions",
    ", signalling that a wider shutdown is imminent",
)
#: Parties for ``claim_as_fact``.
CLAIM_PARTIES = ("A spokesman for the opposition", "A partisan news channel",
                 "An anonymous online account", "A rival company's statement")

_MONTHS = ("January", "February", "March", "April", "May", "June", "July",
           "August", "September", "October", "November", "December")


@dataclass(frozen=True)
class SeatItem:
    """One item a verifier is measured on: ``truth`` is ``"true"`` or the
    planted kind."""

    item_id: str
    truth: str
    statement: StatementDraft
    support: tuple[SupportRow, ...]
    texts: EvidenceTexts
    subject_names: tuple[str, ...]
    base_id: str

    @property
    def planted(self) -> bool:
        return self.truth != TRUE


def from_canary(item: CanaryItem) -> SeatItem:
    return SeatItem(item.item_id, TRUE, item.statement, item.support, item.texts,
                    item.subject_names, item.item_id)


