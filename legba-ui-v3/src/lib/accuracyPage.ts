export interface AccuracyInputs {
  roster?: GraderRoster | null
  critic?: ScorecardRow[] | null
  correctness?: UnitCorrectnessBoard | null
  calibration?: CalibrationScoreboard | null
  since?: JudgmentSince | null
  /** When the client read the live-count routes (`/v3/eval/correctness`
   *  carries no read stamp of its own). ISO. */
  readAt?: string | null
  /** Routes that have not answered yet. A pending route's figures read `—`
   *  "reading <route>" — never *unmeasured*, which would claim an answer. */
  pending?: Partial<Record<RouteKey, boolean>>
}

export type RouteKey = 'roster' | 'critic' | 'correctness' | 'calibration' | 'since'

export const ROUTE_PATH: Record<RouteKey, string> = {
  roster: '/v3/eval/grader_roster',
  critic: '/v3/eval/scorecard',
  correctness: '/v3/eval/correctness',
  calibration: '/v3/eval/calibration',
  since: '/v3/since',
}

export function isPending(i: AccuracyInputs, k: RouteKey): boolean {
  return i.pending?.[k] === true
}

/** A figure whose route has not answered yet: a dash that says so. */
export function reading(unit: string, k: RouteKey): FigureData {
  return { state: 'dash', unit, asOf: { absent: `reading ${ROUTE_PATH[k]}` } }
}

/** `fig`, unless the route is still being read. */
function figOf(i: AccuracyInputs, k: RouteKey, value: unknown, unit: string, asOf: AsOf): FigureData {
  return isPending(i, k) ? reading(unit, k) : fig(value, unit, asOf)
}

function rosterOf(i: AccuracyInputs): GraderRoster | null {
  const r = obj<GraderRoster>(i.roster)
  return r && r.available && obj(r.roster) ? r : null
}

function correctnessOf(i: AccuracyInputs): UnitCorrectnessBoard | null {
  return obj<UnitCorrectnessBoard>(i.correctness)
}

function calibrationOf(i: AccuracyInputs): CalibrationScoreboard | null {
  const c = obj<CalibrationScoreboard>(i.calibration)
  return c && c.available ? c : null
}

function criticOf(i: AccuracyInputs): ScorecardRow[] {
  return Array.isArray(i.critic) ? i.critic : []
}

