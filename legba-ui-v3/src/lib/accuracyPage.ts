/**
 * The Accuracy page (`system.eval_scorecard`, UI-1) — its pure model.
 *
 * The page is the roster-wide answer to "is what it produced any good?",
 * folded onto our objects (units × the profile's subject roster) after the
 * World Monitor accuracy page's PATTERN (research note §4; never its prose):
 *
 *   1. the cohort paragraph — which units over which roster, the windows, the
 *      as-ofs — generated from the routes and the profile, never hand-written;
 *   2. the sealed ledgers: the operator gold set as a stage table (entries →
 *      resolved → scored → voided → awaiting a judge, every stage a count WITH
 *      its denominator and its as-of); the forecast ledger is NOT modelled
 *      here — the page mounts its one home, `panels/ledger/ForecastLedger`;
 *   3. calibration (its own section file);
 *   4. the grader roster: per grader the graded count, the population it was
 *      drawn from, what was kept out, and the as-of;
 *   5. *what this page does not publish* — `not_published.json`, generated by
 *      `scripts/gen_not_published.py` from docs/SEAMS.md and the routes' own
 *      declared unmeasured classes, with the live figure each class has.
 *
 * Every number leaves here as a `FigureData` (`lib/Figure.tsx`): a value, its
 * unit, its as-of, or an absence state with the reason. A null is never a 0;
 * a measured 0 stays a 0 (UI-D1 §6). Nouns come from the profile
 * (`lib/profileUi.ts`) — the platform's words where it declares none.
 */
