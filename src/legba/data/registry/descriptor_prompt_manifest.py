"""The descriptor-prompt manifest, one file per descriptor (R-1).

``scripts/gen_descriptor_prompt_manifest.py`` compiles the tree's descriptor
prompts and declared states into package data the R4 drift gauges compare the
live registry against (``production_gauge_integrity``). It used to write ONE
file, ``descriptor_prompts.json``, which every lane that added or edited a
descriptor regenerated: fourteen commits in two days touched it, and two
commits existed only to regenerate it after a lane left it stale.

Now the manifest is a DIRECTORY, ``descriptor_prompts/``, with one small JSON
per descriptor file that contributes a prompt or a state (named after the
YAML file). Two lanes touching different descriptors touch different files.
:func:`load_manifest` assembles exactly the dict the single file held
(``manifest_version``, ``note``, ``prompts``, ``states``), so every reader is
unchanged. A key that two files both claim is refused (``ValueError``), never
resolved by load order.

Stdlib only: read by the registry's production gauge in the slim image.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

__all__ = ["MANIFEST_DIR", "MANIFEST_NOTE", "MANIFEST_VERSION", "load_manifest"]

#: The package-data directory (ships inside the wheel like the old file did).
MANIFEST_DIR = Path(__file__).with_name("descriptor_prompts")

#: Bumped when the manifest's SHAPE changes (v2 added ``states``).
MANIFEST_VERSION = 2

MANIFEST_NOTE = (
    "Generated by scripts/gen_descriptor_prompt_manifest.py. Do not edit "
    "by hand — regenerate. Guarded by "
    "tests/data_pkg/test_production_gauge_integrity.py."
)

_SECTIONS = ("prompts", "states")


def load_manifest(directory: Path | None = None) -> dict[str, Any]:
    """The whole manifest, assembled from ``directory`` (default: the shipped
    one). Raises ``OSError`` when the directory is absent and ``ValueError``
    on unreadable JSON or a key claimed twice — the gauge reports either as
    ``prompt_manifest_unavailable`` rather than as zero drift."""
    directory = directory or MANIFEST_DIR
    if not directory.is_dir():
        raise FileNotFoundError(f"prompt manifest directory absent: {directory}")
    out: dict[str, Any] = {
        "manifest_version": MANIFEST_VERSION,
        "note": MANIFEST_NOTE,
        "prompts": {},
        "states": {},
    }
    for path in sorted(directory.glob("*.json")):
        part = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(part, dict) or set(part) - set(_SECTIONS):
            raise ValueError(f"{path.name}: expected only {list(_SECTIONS)}")
        for section in _SECTIONS:
            for key, entry in (part.get(section) or {}).items():
                if key in out[section]:
                    raise ValueError(f"{section} key {key!r} claimed twice ({path.name})")
                out[section][key] = entry
    for section in _SECTIONS:
        out[section] = dict(sorted(out[section].items()))
    return out
