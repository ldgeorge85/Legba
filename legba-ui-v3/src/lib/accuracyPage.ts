/** What a route class shows from the live response: a figure, a sentence, or nothing. */
export interface LiveReading {
  figure?: FigureData
  text?: string
}

type LiveResolver = (i: AccuracyInputs, ui: ProfileUi) => LiveReading | null

/** The live readings a generated route class may name. The generator's
 *  `live` keys and this table are pinned to each other by a test. */
export const LIVE_RESOLVERS: Record<string, LiveResolver> = {
  'grader_roster.unmeasured': (i, ui) => {
    const r = rosterOf(i)
    if (!r) return { text: 'the grader roster has graded nothing in its window — unmeasured, not zero' }
    return {
      figure: fig(r.roster.desks_unmeasured, `${nouns(ui).pairs} unmeasured this window`, asOfFrom(r.as_of, 'the grader roster carries no as-of')),
    }
  },
  'calibration.forecast_status': (i) => {
    const c = calibrationOf(i)
    if (!c) return { text: 'no calibration finding has been computed — no pilot yet, not a failed one' }
    return c.forecast_acute_status ? { text: `today: ${c.forecast_acute_status}` } : null
  },
  'correctness.below_floor': (i, ui) => {
    const c = correctnessOf(i)
    if (!c || !Array.isArray(c.units)) return null
    return {
      figure: fig(
        c.units.filter((u) => !u.sufficient).length,
        `${nouns(ui).units} below their verdict floor`,
        asOfFrom(i.readAt, 'the route did not answer', READ_LIVE),
      ),
    }
  },
  'correctness.external_truth': (i) => {
    const t = obj<ExternalTruthBoard>(correctnessOf(i)?.external_truth)
    if (!t?.headline) return null
    return { text: `today: ${t.headline.record?.display ?? '—'} · ${t.headline.voice?.display ?? '—'}` }
  },
}

/** The route each live key reads — while it is pending the reading says so. */
const LIVE_ROUTE: Record<string, RouteKey> = {
  'grader_roster.unmeasured': 'roster',
  'calibration.forecast_status': 'calibration',
  'correctness.below_floor': 'correctness',
  'correctness.external_truth': 'correctness',
}

export function liveReading(cls: NotPublishedRouteClass, i: AccuracyInputs, ui: ProfileUi = PROFILE_UI): LiveReading | null {
  if (!cls.live) return null
  const route = LIVE_ROUTE[cls.live]
  if (route && isPending(i, route)) return { text: `reading ${ROUTE_PATH[route]}…` }
  const resolve = LIVE_RESOLVERS[cls.live]
  return resolve ? resolve(i, ui) : null
}
