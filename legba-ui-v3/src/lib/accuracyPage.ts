export interface GraderRow {
  id: string
  grader: string
  route: string
  graded: FigureData
  population: { label: string; figure: FigureData }
  keptOut: { label: string; figure: FigureData } | null
  note?: string
}

const NOT_GRADED_STATES = new Set([CARRIED_UNGRADED, 'unassessable'])

export function graderRows(i: AccuracyInputs, ui: ProfileUi = PROFILE_UI): GraderRow[] {
  const n = nouns(ui)
  const out: GraderRow[] = []

  // The machine correctness grader — the roster route.
  const roster = rosterOf(i)
  if (isPending(i, 'roster')) {
    out.push({
      id: 'machine',
      grader: 'correctness grader',
      route: ROUTE_PATH.roster,
      graded: reading(n.pairs, 'roster'),
      population: { label: 'on the roster', figure: reading(n.pairs, 'roster') },
      keptOut: null,
    })
  } else if (roster) {
    const asOf = asOfFrom(roster.as_of, 'the grader roster carries no as-of')
    const t = roster.roster
    out.push({
      id: 'machine',
      grader: `correctness grader, ${roster.grain} grain, ${roster.nights} nights`,
      route: '/v3/eval/grader_roster',
      graded: fig(t.desks_graded, n.pairs, asOf),
      population: { label: 'on the roster', figure: fig(t.desks_graded + t.desks_unmeasured, n.pairs, asOf) },
      keptOut: { label: 'unmeasured — the reference decided nothing they said', figure: fig(t.desks_unmeasured, n.pairs, asOf) },
    })
  } else {
    const why: AsOf = { absent: 'nothing graded inside the window' }
    out.push({
      id: 'machine',
      grader: 'correctness grader',
      route: '/v3/eval/grader_roster',
      graded: { state: 'unmeasured', unit: n.pairs, asOf: why },
      population: { label: 'on the roster', figure: { state: 'unmeasured', unit: n.pairs, asOf: why } },
      keptOut: null,
    })
  }

  // The operator gold set.
  const goldFig = (value: unknown, unit: string, asOf: AsOf) => figOf(i, 'correctness', value, unit, asOf)
  const corr = correctnessOf(i)
  const fleet = obj<NonNullable<UnitCorrectnessBoard['fleet']>>(corr?.fleet)
  const goldAsOf: AsOf = fleet
    ? asOfFrom(i.readAt, 'the route did not answer', READ_LIVE)
    : { absent: 'no operator verdict was read' }
  out.push({
    id: 'goldset',
    grader: 'operator gold set',
    route: '/v3/eval/correctness',
    graded: goldFig(fleet?.n_scored, 'verdicts', goldAsOf),
    population: { label: 'labelled', figure: goldFig(fleet?.n_labels, 'verdicts', goldAsOf) },
    keptOut: { label: 'unresolvable — out of both numerator and denominator', figure: goldFig(fleet?.n_unresolvable, 'verdicts', goldAsOf) },
    note: fleet?.status,
  })

  // The critic judge — the newest page of judgements.
  const rows = criticOf(i)
  const stamps = rows.map((r) => r.produced_at).filter((s) => stampOf(s) !== null).sort()
  const criticAsOf = asOfFrom(stamps[stamps.length - 1], rows.length ? 'no judgement carries a time' : 'no critic judgement read')
  const criticFig = (value: unknown, unit: string) => figOf(i, 'critic', value, unit, criticAsOf)
  const carried = rows.filter((r) => r.score_state === CARRIED_UNGRADED).length
  const unassessable = rows.filter((r) => r.score_state === 'unassessable').length
  out.push({
    id: 'critic',
    grader: 'critic judge',
    route: '/v3/eval/scorecard',
    graded: criticFig(rows.length ? rows.filter((r) => !NOT_GRADED_STATES.has(r.score_state ?? '')).length : null, 'judgements'),
    population: { label: 'the newest page read', figure: criticFig(rows.length ? rows.length : null, 'judgements') },
    keptOut: rows.length ? { label: absencePhrase('carried_ungraded'), figure: fig(carried, 'judgements', criticAsOf) } : null,
    note: rows.length ? `${unassessable} unassessable, also kept out of every mean` : undefined,
  })

  // The calibration tracker — the exogenous Brier.
  const cal = calibrationOf(i)
  const calAsOf = asOfFrom(cal?.produced_at, 'no calibration finding has been computed')
  out.push({
    id: 'calibration',
    grader: 'calibration tracker (exogenous Brier) — untrusted, legacy, under diagnosis',
    route: '/v3/eval/calibration',
    graded: figOf(i, 'calibration', cal?.exogenous_sample_size, 'claims', calAsOf),
    population: { label: 'tracked', figure: figOf(i, 'calibration', cal?.pooled_sample_size, 'claims', calAsOf) },
    keptOut: null,
  })

  // Standing external truth — one row per population, never summed.
  const truth = obj<ExternalTruthBoard>(corr?.external_truth)
  const days = obj<{ days?: number }>(truth?.window)?.days
  const truthAsOf: AsOf = {
    absent: `the block carries no as-of${isNum(days) ? `; trailing ${days}-day window` : ''}`,
  }
  if (truth?.available && Array.isArray(truth.populations) && truth.populations.length) {
    for (const p of truth.populations) {
      out.push({
        id: `truth-${p.population}`,
        grader: `external truth · ${p.label || p.population}`,
        route: '/v3/eval/correctness · external_truth',
        graded: fig(p.n_decided, 'claims decided', truthAsOf),
        population: { label: 'searched', figure: fig(p.n_searched, 'claims', truthAsOf) },
        keptOut: { label: 'not found — a statement about the search', figure: fig(p.not_found, 'claims', truthAsOf) },
      })
    }
  } else {
    out.push({
      id: 'truth',
      grader: 'external truth',
      route: '/v3/eval/correctness · external_truth',
      graded: isPending(i, 'correctness') ? reading('claims decided', 'correctness') : { state: 'unmeasured', unit: 'claims decided', asOf: truthAsOf },
      population: {
        label: 'searched',
        figure: isPending(i, 'correctness') ? reading('claims', 'correctness') : { state: 'unmeasured', unit: 'claims', asOf: truthAsOf },
      },
      keptOut: null,
      note: truth?.headline
        ? `${truth.headline.record?.display ?? ''} · ${truth.headline.voice?.display ?? ''}`
        : undefined,
    })
  }
  return out
}

