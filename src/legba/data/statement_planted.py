def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float] | None:
    """The 95 % Wilson interval for ``k`` of ``n`` (``None`` when n = 0)."""
    if n <= 0:
        return None
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (round(max(0.0, centre - half), 4), round(min(1.0, centre + half), 4))


@dataclass(frozen=True)
class Rate:
    k: int
    n: int

    @property
    def value(self) -> float | None:
        return round(self.k / self.n, 4) if self.n else None

    def as_dict(self) -> dict[str, Any]:
        return {"k": self.k, "n": self.n, "rate": self.value, "wilson95": wilson(self.k, self.n)}


def score(results: Iterable[tuple[SeatItem, VerifierReport]]) -> dict[str, Any]:
    """Catch and false-reject rates, seat and model, overall and per kind.

    Seat: caught = not established (code refusal or a non-``supports`` model
    verdict). Model: caught = a readable verdict other than ``supports``;
    unreadable replies are counted apart and left out of the model's rate."""
    seat_c = seat_n = model_c = model_n = 0
    seat_fr = seat_t = model_fr = model_t = 0
    unparsed = 0
    per_kind: dict[str, list[int]] = {}
    for item, rep in results:
        readable = rep.decided_by == "model" and rep.verdict != UNCLEAR
        if rep.decided_by in {"unparsed", "no_call"}:
            unparsed += 1
        if item.planted:
            seat_n += 1
            seat_c += int(not rep.establishes)
            row = per_kind.setdefault(item.truth, [0, 0, 0, 0])
            row[0] += int(not rep.establishes)
            row[1] += 1
            if readable:
                model_n += 1
                model_c += int(rep.verdict != SUPPORTS)
                row[2] += int(rep.verdict != SUPPORTS)
                row[3] += 1
        else:
            seat_t += 1
            seat_fr += int(not rep.establishes)
            if readable:
                model_t += 1
                model_fr += int(rep.verdict != SUPPORTS)
    catch = Rate(seat_c, seat_n)
    return {
        "seat_catch": catch.as_dict(),
        "seat_false_reject": Rate(seat_fr, seat_t).as_dict(),
        "model_catch": Rate(model_c, model_n).as_dict(),
        "model_false_reject": Rate(model_fr, model_t).as_dict(),
        "unparsed_or_uncalled": unparsed,
        "per_kind": {k: {"seat": Rate(v[0], v[1]).as_dict(), "model": Rate(v[2], v[3]).as_dict()}
                     for k, v in sorted(per_kind.items())},
        "floors": {"catch": CATCH_FLOOR, "false_reject": FALSE_REJECT_CEILING},
        "establishment_paused": establishment_paused(catch.value),
    }


def establishment_paused(catch_rate: float | None, *, floor: float = CATCH_FLOOR) -> bool:
    """True when establishment must pause: no measured rate, or one below the
    floor. Candidates accumulate meanwhile; nothing is lost."""
    return catch_rate is None or catch_rate < floor


