export interface NotPublishedSeam {
  id: string
  seam: number
  title: string
  summary: string
  guard: string
  source: string
}

export interface NotPublishedRouteClass {
  id: string
  route: string
  source: string
  text: string
  live: string | null
}

export interface NotPublishedDoc {
  schema: string
  seams: NotPublishedSeam[]
  route_classes: NotPublishedRouteClass[]
}

function strOf(v: unknown): string {
  return typeof v === 'string' ? v : ''
}

/** Read a `legba/not_published/1` document defensively. */
export function notPublishedFrom(doc: unknown): NotPublishedDoc {
  const d = obj<Record<string, unknown>>(doc) ?? {}
  const list = (v: unknown) => (Array.isArray(v) ? v.map((x) => obj<Record<string, unknown>>(x) ?? {}) : [])
  return {
    schema: strOf(d.schema),
    seams: list(d.seams)
      .filter((s) => isNum(s.seam) && strOf(s.title))
      .map((s) => ({
        id: strOf(s.id),
        seam: s.seam as number,
        title: strOf(s.title),
        summary: strOf(s.summary),
        guard: strOf(s.guard),
        source: strOf(s.source),
      })),
    route_classes: list(d.route_classes)
      .filter((r) => strOf(r.id) && strOf(r.text))
      .map((r) => ({
        id: strOf(r.id),
        route: strOf(r.route),
        source: strOf(r.source),
        text: strOf(r.text),
        live: typeof r.live === 'string' ? r.live : null,
      })),
  }
}

