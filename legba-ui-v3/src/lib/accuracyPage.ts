export interface CohortModel {
  profile: string
  nouns: Nouns
  /** The profile's unit roster as words, or null when it declares none. */
  units: string[] | null
  /** The roster labels the profile scores (its subject rosters). */
  rosters: string[]
  grader: { pairs: FigureData; subjects: FigureData; nights: number | null; grain: string | null } | null
  critic: { judgements: FigureData; oldest: string | null; newest: string | null } | null
  goldWeeks: FigureData
  calibrationAsOf: AsOf
  /** Which cohort clauses are still waiting on their route. */
  pending: { grader: boolean; critic: boolean }
}

export function cohortModel(i: AccuracyInputs, ui: ProfileUi = PROFILE_UI): CohortModel {
  const n = nouns(ui)
  const tags = ui.rosters.scored_subject_tags.length ? ui.rosters.scored_subject_tags : ui.rosters.subject_tags
  const roster = rosterOf(i)
  let grader: CohortModel['grader'] = null
  if (roster) {
    const asOf = asOfFrom(roster.as_of, 'the grader roster carries no as-of')
    const desks = Array.isArray(roster.desks) ? roster.desks : []
    grader = {
      pairs: fig(roster.roster.desks_graded + roster.roster.desks_unmeasured, n.pairs, asOf),
      subjects: fig(new Set(desks.map((d) => d.target_id)).size, n.subjects, asOf),
      nights: isNum(roster.nights) ? roster.nights : null,
      grain: typeof roster.grain === 'string' ? roster.grain : null,
    }
  }
  const rows = criticOf(i)
  const stamps = rows.map((r) => r.produced_at).filter((s) => stampOf(s) !== null).sort()
  const critic = rows.length
    ? {
        judgements: fig(rows.length, 'critic judgements', asOfFrom(stamps[stamps.length - 1], 'no judgement carries a time')),
        oldest: stampOf(stamps[0]),
        newest: stampOf(stamps[stamps.length - 1]),
      }
    : null
  const corr = correctnessOf(i)
  const weeksPinned = corr?.labeling?.weeks_pinned
  const cal = calibrationOf(i)
  return {
    profile: ui.profile,
    nouns: n,
    units: ui.rosters.units ? ui.rosters.units.map(unitWords) : null,
    rosters: tags.map((t) => rosterLabel(t, ui)),
    grader,
    critic,
    goldWeeks: figOf(i, 'correctness', weeksPinned, 'weeks pinned', asOfFrom(i.readAt, 'the route did not answer', READ_LIVE)),
    calibrationAsOf: isPending(i, 'calibration')
      ? { absent: `reading ${ROUTE_PATH.calibration}` }
      : asOfFrom(cal?.produced_at, 'no calibration finding has been computed'),
    pending: { grader: isPending(i, 'roster'), critic: isPending(i, 'critic') },
  }
}

